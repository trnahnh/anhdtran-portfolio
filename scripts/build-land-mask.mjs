/**
 * Build the land mask the Flight Log globe draws its dots from.
 *
 * Fetches Natural Earth's 1:110m land polygons (via the world-atlas package on
 * jsDelivr), samples a 1° grid at cell centres, and writes
 * lib/data/landMask.ts: one bit per cell, row-major from 89.5°N down to
 * 89.5°S and from 179.5°W east, packed and base64-encoded (~11 KB).
 *
 * Run by hand; one-off tooling, not a build step:
 *
 *     node scripts/build-land-mask.mjs
 */

import { writeFile } from "node:fs/promises";

const SRC = "https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-110m.json";
const OUT = new URL("../lib/data/landMask.ts", import.meta.url);
const COLS = 360;
const ROWS = 180;

const topo = await (await fetch(SRC)).json();

// TopoJSON arcs are quantized and delta-encoded.
const { scale, translate } = topo.transform;
const arcs = topo.arcs.map((arc) => {
  let x = 0;
  let y = 0;
  return arc.map(([dx, dy]) => {
    x += dx;
    y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});

function ring(indices) {
  const pts = [];
  for (const i of indices) {
    const arc = i < 0 ? arcs[~i].slice().reverse() : arcs[i];
    pts.push(...(pts.length ? arc.slice(1) : arc));
  }
  return pts;
}

const rings = [];
const collect = (g) => {
  if (g.type === "GeometryCollection") g.geometries.forEach(collect);
  else if (g.type === "Polygon") g.arcs.forEach((r) => rings.push(ring(r)));
  else if (g.type === "MultiPolygon")
    g.arcs.forEach((p) => p.forEach((r) => rings.push(ring(r))));
};
collect(topo.objects.land);

// Bounding boxes let most rings skip the ray cast entirely.
const boxed = rings.map((pts) => {
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (const [x, y] of pts) {
    x0 = Math.min(x0, x); x1 = Math.max(x1, x);
    y0 = Math.min(y0, y); y1 = Math.max(y1, y);
  }
  return { pts, x0, y0, x1, y1 };
});

// Even-odd across every ring: land polygons never overlap, so holes come out
// right without tracking which ring is outer.
function isLand(lon, lat) {
  let inside = false;
  for (const { pts, x0, y0, x1, y1 } of boxed) {
    if (lon < x0 || lon > x1 || lat < y0 || lat > y1) continue;
    for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
      const [xi, yi] = pts[i];
      const [xj, yj] = pts[j];
      if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) {
        inside = !inside;
      }
    }
  }
  return inside;
}

const bytes = new Uint8Array((COLS * ROWS) / 8);
let land = 0;
for (let r = 0; r < ROWS; r++) {
  for (let c = 0; c < COLS; c++) {
    if (isLand(-179.5 + c, 89.5 - r)) {
      const bit = r * COLS + c;
      bytes[bit >> 3] |= 0x80 >> (bit & 7);
      land++;
    }
  }
}

const b64 = Buffer.from(bytes).toString("base64");
await writeFile(
  OUT,
  `// Generated by scripts/build-land-mask.mjs from Natural Earth 1:110m land.
// One bit per 1° cell, row-major from 89.5°N and 179.5°W. Do not edit.
export const LAND_COLS = ${COLS};
export const LAND_ROWS = ${ROWS};
export const LAND_MASK =
  "${b64}";
`,
);
console.log(`${land} land cells of ${COLS * ROWS}`);
